//  可跨线程的剪贴板值快照：NSPasteboardItem 不能离开主线程，贵的解析放到后台。
//

import AppKit
import Foundation

nonisolated struct PasteboardSnapshot: Sendable {
    /// 一次复制里的每个 pasteboard item，顺序即剪贴板里的顺序。
    let items: [Item]

    struct Item: Sendable {
        let values: [String: Data]

        init(values: [String: Data] = [:]) {
            self.values = values
        }

        func data(_ type: NSPasteboard.PasteboardType) -> Data? {
            values[type.rawValue]
        }

        /// 该类型按 UTF-8 解码；捕获时已由 AppKit 定好编码。
        func string(_ type: NSPasteboard.PasteboardType) -> String? {
            guard let data = values[type.rawValue] else { return nil }
            return String(data: data, encoding: .utf8)
        }
    }

    /// 字符串类类型，读时让 AppKit 转换编码；`.URL` 是 public.url。
    private static let stringTypes: [NSPasteboard.PasteboardType] = [.string, .fileURL, .URL]
    /// 字节类类型：PNG/TIFF、RTF、HTML、颜色。
    private static let dataTypes: [NSPasteboard.PasteboardType] = [.png, .tiff, .rtf, .html, .color]

    /// 「不要记录」类型（nspasteboard.org 约定）；只按来源忽略会漏掉密码管理器。
    static let doNotRecordTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.apple.is-remote-clipboard",
    ]

    /// 这次复制是否被标记为「不要记录」。只看类型、不读任何字节。
    @MainActor
    static func isMarkedDoNotRecord(_ items: [NSPasteboardItem]) -> Bool {
        items.contains { item in
            item.types.contains { doNotRecordTypes.contains($0.rawValue) }
        }
    }

    /// 读一次快照；只能在主线程调用，之后解析与 bookmark 固化转到后台。
    @MainActor
    static func capture(from items: [NSPasteboardItem]) -> PasteboardSnapshot {
        PasteboardSnapshot(items: items.map { item in
            var values: [String: Data] = [:]
            for type in stringTypes {
                if let string = item.string(forType: type) {
                    values[type.rawValue] = Data(string.utf8)
                }
            }
            for type in dataTypes {
                // 同时提供 PNG/TIFF 时只留 PNG：解析器本来就优先 PNG，避免主线程重复拷一份位图。
                if type == .tiff,
                   let png = values[NSPasteboard.PasteboardType.png.rawValue],
                   PasteboardFormat.isBitmap(png) {
                    continue
                }
                if let data = item.data(forType: type) {
                    values[type.rawValue] = data
                }
            }
            return Item(values: values)
        })
    }
}
